/**
 * What the controls are allowed to say, computed from the generated record at
 * build time.
 *
 * BUILD TIME, NOT RUNTIME, AND THAT IS THE POINT. Every number a control
 * displays is arithmetic over `src/data/scene/payload/*.bin` performed while
 * the page is being generated, so it lands in the HTML as text. A reader with
 * scripting off, a reader whose canvas never starts and a screen-reader user
 * all get the same figures, and no control can display a number the record does
 * not contain because there is nowhere for one to come from.
 *
 * WHAT MAY NOT BE COMPUTED HERE, restated because the temptation is structural.
 * `design/scene/EVIDENCE-VERDICTS.md` §5 rules that the reward-composition
 * counterfactual, the one with 25% of rollouts moved and 2,118 sign reversals,
 * has no per-item artifact in either published repository. It may be stated in
 * prose with its limitation and it may not become geometry or a control's
 * displayed result. So the score-component control below binds to the 200-step
 * record instead and states that record's own result, which is a negative: the
 * run's score tree has exactly one leaf, and a decomposition with one part
 * cannot be redistributed.
 *
 * This module runs in Node during the Astro build. It must not be imported by
 * anything that ships to the browser.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";
import manifestJson from "../../data/scene/manifest.json";
import captionsJson from "../../data/scene/captions.json";
import {
  decodeScenePayload,
  sceneCaseById,
  type ScenePayload,
  type SceneCaptionFile,
} from "../../data/schema/scene";
import type { SceneCase, SceneManifest } from "../scene/types/truth";

export const manifest = manifestJson as unknown as SceneManifest;
const captions = captionsJson as unknown as SceneCaptionFile;

const payloadCache = new Map<string, ScenePayload>();

/**
 * One case's arrays, read off disk once per build.
 *
 * The path is resolved from the working directory rather than from
 * `import.meta.url`, and that is not a shortcut. This module is bundled into
 * `dist/pages/` before it runs, so `import.meta.url` at execution time points
 * inside the build output, where `src/data/scene/payload/` does not exist. The
 * first build failed exactly there. Astro runs from the project root, in the
 * build and under the dev server alike, so the root is where the record is.
 */
export function payloadFor(caseId: string): ScenePayload {
  const cached = payloadCache.get(caseId);
  if (cached) return cached;
  const path = join(process.cwd(), "src", "data", "scene", "payload", `${caseId}.bin`);
  let bytes: Buffer;
  try {
    bytes = readFileSync(path);
  } catch {
    throw new Error(
      `scene-controls: no generated payload at ${path}. The scene record is generated by ` +
        `\`npm run build:scene-data\`, and a control may not display a number that is not in it.`,
    );
  }
  const decoded = decodeScenePayload(bytes);
  payloadCache.set(caseId, decoded);
  return decoded;
}

export function caseById(id: string): SceneCase {
  return sceneCaseById(manifest, id);
}

export function captionFor(id: string): string {
  return captions.captions[id]?.text ?? "";
}

/**
 * Thousands separators without the host's locale data, which is the same reason
 * the generator has its own. A build that formats numbers differently on two
 * machines produces two different pages from one commit.
 */
export function group(n: number): string {
  const [whole, frac] = String(n).split(".");
  const sign = whole.startsWith("-") ? "-" : "";
  const digits = sign ? whole.slice(1) : whole;
  const parts: string[] = [];
  for (let i = digits.length; i > 0; i -= 3) parts.unshift(digits.slice(Math.max(0, i - 3), i));
  return sign + parts.join(",") + (frac ? `.${frac}` : "");
}

/** A signed value with a fixed number of places, so a column does not ripple. */
export function signed(v: number, places = 3): string {
  const s = v.toFixed(places);
  return v > 0 ? `+${s}` : s.startsWith("-") ? s : s === (0).toFixed(places) ? s : `+${s}`;
}

// ---------------------------------------------------------------------------
// The score-component control
// ---------------------------------------------------------------------------

export interface ScoreComponentFacts {
  /** The leaf's own name in the record. Rendered as code, never as prose. */
  leafName: string;
  leafCount: number;
  rolloutCount: number;
  scoredRolloutCount: number;
  abstainedRolloutCount: number;
  /** Rollouts the estimator gave a positive advantage: reinforced. */
  reinforcedCount: number;
  /** Rollouts given a negative advantage: pushed away from. */
  discouragedCount: number;
  /** Rollouts whose recorded advantage is exactly zero. */
  onAxisCount: number;
}

/**
 * The one score component this run has, and what happens to the update when it
 * is taken away.
 *
 * The arithmetic is trivial and that is the finding. The score tree has one
 * leaf, so removing it removes the score for every rollout, and with no score
 * there is no group mean, no advantage and nothing reinforced. The control
 * displays the real counts on both sides of that, and the honest reading is
 * printed beside them: this run cannot show how a reward divides between its
 * parts, because it has one part.
 */
export function scoreComponentFacts(): ScoreComponentFacts {
  const tree = payloadFor("scorer-score-tree");
  const abstained = tree.i32("scores.leaf.abstained");
  const values = tree.f32("scores.leaf.value");
  const leafCount = tree.i32("scores.leafCount")[0];

  const selection = payloadFor("selection-advantages");
  const advantage = selection.f32("advantage");

  let abstainedCount = 0;
  for (const v of abstained) if (v !== 0) abstainedCount += 1;

  let reinforced = 0;
  let discouraged = 0;
  let onAxis = 0;
  for (const v of advantage) {
    if (v > 0) reinforced += 1;
    else if (v < 0) discouraged += 1;
    else onAxis += 1;
  }

  return {
    // The array name in the payload is the artifact's own field path, and the
    // leaf's name is the segment between the slashes. Read rather than typed,
    // so a regenerated record with a different grader renames this by itself.
    leafName: leafNameFromPayload(tree),
    leafCount,
    rolloutCount: values.length,
    scoredRolloutCount: values.length - abstainedCount,
    abstainedRolloutCount: abstainedCount,
    reinforcedCount: reinforced,
    discouragedCount: discouraged,
    onAxisCount: onAxis,
  };
}

function leafNameFromPayload(payload: ScenePayload): string {
  for (const d of payload.descriptors) {
    const match = /^rewards\/(.+)\/mean$/.exec(d.name);
    if (match) return match[1];
  }
  throw new Error(
    "scene-controls: the score-tree payload carries no `rewards/<leaf>/mean` array, so the " +
      "score-component control has no component to name. The generator is " +
      "scripts/build_scene_data.mjs; this control binds to its output and does not invent a name.",
  );
}

// ---------------------------------------------------------------------------
// The trace-one-rollout control
// ---------------------------------------------------------------------------

export interface TracedRollout {
  /** Stable id, derived from the record's own step, group and position. */
  id: string;
  stepIndex: number;
  groupOrdinal: number;
  /** Position within its group, in the order the record lists the rollouts. */
  positionInGroup: number;
  advantage: number;
  groupMean: number;
  groupStd: number;
  groupSize: number;
}

/**
 * The eight rollouts of one recorded step, each with a stable id.
 *
 * Step 0 is chosen because `EVIDENCE-VERDICTS.md` §4 verified its eight signed
 * values directly against the fixture, so this is the one step in the record
 * whose contents have been checked by hand outside the generator. The ids are
 * built from the record's own step index, group ordinal and position within the
 * group rather than from an array index, so a reordered shard cannot silently
 * renumber a rollout out from under a reader who linked to one.
 */
export function tracedRollouts(stepIndex = 0): TracedRollout[] {
  const payload = payloadFor("selection-advantages");
  const advantage = payload.f32("advantage");
  const steps = payload.i32("step_index");
  const groups = payload.i32("group_ordinal");
  const groupMean = payload.f32("group.mean");
  const groupStd = payload.f32("group.std");
  const groupK = payload.i32("group.k");

  const rows: TracedRollout[] = [];
  const seenInGroup = new Map<number, number>();
  // Groups are listed step-major in the group arrays, so a step's groups start
  // at the count of groups the earlier steps used. Read rather than assumed:
  // the record does not promise a fixed group count per step.
  const groupsPerStep = new Map<number, Set<number>>();
  for (let i = 0; i < steps.length; i += 1) {
    const set = groupsPerStep.get(steps[i]) ?? new Set<number>();
    set.add(groups[i]);
    groupsPerStep.set(steps[i], set);
  }
  let groupBase = 0;
  for (const [step, set] of [...groupsPerStep.entries()].sort((a, b) => a[0] - b[0])) {
    if (step >= stepIndex) break;
    groupBase += set.size;
  }

  for (let i = 0; i < steps.length; i += 1) {
    if (steps[i] !== stepIndex) continue;
    const g = groups[i];
    const position = seenInGroup.get(g) ?? 0;
    seenInGroup.set(g, position + 1);
    const groupRow = groupBase + g;
    rows.push({
      id: rolloutId(steps[i], g, position),
      stepIndex: steps[i],
      groupOrdinal: g,
      positionInGroup: position,
      advantage: advantage[i],
      groupMean: groupMean[groupRow],
      groupStd: groupStd[groupRow],
      groupSize: groupK[groupRow],
    });
  }

  if (rows.length === 0) {
    throw new Error(
      `scene-controls: the selection payload holds no rollout at recorded step ${stepIndex}, so the ` +
        `trace control has nothing to isolate. The record is generated by scripts/build_scene_data.mjs.`,
    );
  }
  return rows;
}

/** The one place a rollout's public id is formed. Both halves of the build use it. */
export function rolloutId(step: number, group: number, positionInGroup: number): string {
  return `s${String(step).padStart(3, "0")}-g${group}-r${positionInGroup}`;
}

// ---------------------------------------------------------------------------
// The update state's own figures, for the trace summary
// ---------------------------------------------------------------------------

export interface UpdateStepFacts {
  stepIndex: number;
  gradNormClipped: number;
  trajectoryCount: number;
  reward: number;
  rewardStd: number;
  entropy: number;
}

export function updateStepFacts(stepIndex = 0): UpdateStepFacts {
  const payload = payloadFor("update-step");
  return {
    stepIndex,
    gradNormClipped: payload.f32("grad_norm_clipped")[stepIndex],
    trajectoryCount: payload.i32("n_trajectories")[stepIndex],
    reward: payload.f32("reward")[stepIndex],
    rewardStd: payload.f32("reward_std")[stepIndex],
    entropy: payload.f32("entropy")[stepIndex],
  };
}
