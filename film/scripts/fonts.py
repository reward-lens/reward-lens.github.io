"""Make the site's own two faces visible to Pango, without installing anything.

The site self-hosts four woff2 files in public/fonts (76,436 bytes, HANDOFF.md
trap 4). Pango cannot read woff2, so Manim cannot see them. This decompresses
those exact files to TrueType into film/.fonts and writes a fontconfig document
that adds only that directory.

Two properties this buys, and both matter:

  1. The film's letterforms are the site's letterforms, byte for byte from the
     same source file, rather than a same-named face downloaded separately.
  2. Nothing is installed system-wide. The render sets FONTCONFIG_FILE to the
     generated document, so the machine is unchanged when the render ends.

Run through film/scripts/render.mjs. Idempotent: it rewrites both outputs every
time, which costs milliseconds and removes a stale-cache failure mode.
"""

from __future__ import annotations

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

FILM = Path(__file__).resolve().parent.parent
SITE = FILM.parent
SRC = SITE / "public" / "fonts"
OUT = FILM / ".fonts"

# The four faces the site ships. Nothing else is permitted in the film either.
FACES = [
    "ibm-plex-sans-latin-400-normal.woff2",
    "ibm-plex-sans-latin-600-normal.woff2",
    "ibm-plex-mono-latin-400-normal.woff2",
    "ibm-plex-mono-latin-500-normal.woff2",
]

CONF = """<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<!-- GENERATED by film/scripts/fonts.py. Do not edit. -->
<fontconfig>
  <dir>{dir}</dir>
  <cachedir>{cache}</cachedir>
  <config></config>
</fontconfig>
"""


def family_of(font: TTFont) -> str:
    """The family name Pango will match on, read from the file rather than assumed."""
    for record in font["name"].names:
        if record.nameID == 1:
            return str(record.toUnicode())
    return "?"


def main() -> int:
    if not SRC.is_dir():
        print(f"fonts: {SRC} does not exist", file=sys.stderr)
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "cache").mkdir(exist_ok=True)

    families = set()
    for name in FACES:
        source = SRC / name
        if not source.is_file():
            print(f"fonts: missing {source}", file=sys.stderr)
            return 1
        font = TTFont(str(source))
        target = OUT / (name.replace(".woff2", ".ttf"))
        font.flavor = None
        font.save(str(target))
        families.add(family_of(font))

    (OUT / "fonts.conf").write_text(
        CONF.format(dir=OUT, cache=OUT / "cache"), encoding="utf-8"
    )
    print("fonts: " + ", ".join(sorted(families)) + f" -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
